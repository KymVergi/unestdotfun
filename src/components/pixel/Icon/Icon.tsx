export type IconName = keyof typeof ICONS;

export interface IconProps {
  name: IconName;
  /** Rendered size in CSS pixels. Keep to multiples of 12 for crisp edges. */
  size?: number;
  className?: string;
  title?: string;
}

/** Pre-computed run-length data — the grids never change, so do it once. */
const RUNS = Object.fromEntries(
  (Object.keys(ICONS) as IconName[]).map((name) => {
    const grid = fromRows([...ICONS[name]]);
    return [name, { runs: toRuns(grid), w: grid.w, h: grid.h }];
  }),
) as Record<IconName, { runs: ReturnType<typeof toRuns>; w: number; h: number }>;

export function Icon({ name, size = 12, className, title }: IconProps) {
  const { runs, w, h } = RUNS[name];

  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox={`0 0 ${w} ${h}`}
      shapeRendering="crispEdges"
      fill="currentColor"
      role={title ? 'img' : 'presentation'}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      {runs.map((run) => (
        <rect key={`${run.x}-${run.y}`} x={run.x} y={run.y} width={run.len} height={1} />
      ))}
    </svg>
  );
}

export default Icon;
